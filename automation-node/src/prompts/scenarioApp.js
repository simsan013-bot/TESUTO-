function buildStepUser(design, title, stepName, prevText, currentText, minChars) {
  var msg = 'シナリオ設計：\n' + design + '\n\nタイトル：「' + title + '」\n\n';
  if (prevText) {
    msg += '【前のSTEPまでの台本（参照用）】\n' + prevText + '\n\n';
  }
  if (currentText) {
    msg += '【現在のテキスト（これを基に書き直す）】\n' + currentText + '\n\n';
    msg += '上記の現在のテキストを踏まえて、' + stepName + ' を必要文字数(' + minChars + '字以上)を達成するよう書き直してください。';
  } else {
    msg += '上記をもとに ' + stepName + ' を執筆してください。このSTEPのみを出力してください。';
  }
  return msg;
}

