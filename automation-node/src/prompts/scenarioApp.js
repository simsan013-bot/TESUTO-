function getRandomNameTable(count) {
  count = count || 10;
  var pool = NAME_DATA.slice();
  for (var i = pool.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var tmp = pool[i]; pool[i] = pool[j]; pool[j] = tmp;
  }
  var selected = pool.slice(0, Math.min(count, pool.length));
  var header = '姓     | 20代女性         | 30-40代女性      | 50代以上女性     | 20代男性         | 30-40代男性      | 50代以上男性\n';
  var rows = selected.map(function(r) {
    return r[0] + ' | ' + r[1] + ' | ' + r[2] + ' | ' + r[3] + ' | ' + r[4] + ' | ' + r[5] + ' | ' + r[6];
  });
  return '【登場人物名前選定ルール】同一姓の重複禁止。世代と性別の一致を必ず確認。\n'
    + header + rows.join('\n');
}

