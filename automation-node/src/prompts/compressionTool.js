// STORY_BIBLE をフェーズプロンプトに挿入するヘルパー
function bibleBlock(storyBible) {
  if (!storyBible) return '';
  return '\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n'
    + '【⚠ STORY_BIBLE（全フェーズ必ず遵守・キャラ名・設定・伏線の一貫性を保つこと）】\n'
    + storyBible + '\n'
    + '━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';
}

