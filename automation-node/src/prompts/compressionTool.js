// charReminder ヘルパー（全フェーズプロンプトに挿入）
function charReminder(chars) {
  if (chars) {
    return '\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n'
      + '【⚠ キャラクター設定（全セリフで必ず遵守）】\n'
      + chars + '\n'
      + '・元シナリオのセリフをそのまま流用禁止。必ず各キャラの口調で再構築すること\n'
      + '・説明口調・書き言葉・確認のみのリアクション台詞は全て排除すること\n'
      + '・ナレーションは話し言葉として自然な語りにすること\n'
      + '━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';
  } else {
    return '\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n'
      + '【⚠ セリフ品質チェック（全セリフに適用）】\n'
      + '・説明口調・書き言葉・確認のみのリアクション台詞は全て排除すること\n'
      + '・ナレーションは話し言葉として自然な語りにすること\n'
      + '━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n';
  }
}

